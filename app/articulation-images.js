  function describe(phone) {
    if (typeof phone !== 'string') return null;
    let symbol = phone.normalize('NFC').trim().replace(/^[\/\[]+|[\/\]]+$/gu, '').replace(/[ˈˌ͜͡]/gu, '');
    if (symbol === 'g') symbol = 'ɡ';
    if (symbol === 'i') symbol = 'iː';
    return Object.prototype.hasOwnProperty.call(images, symbol) ? { ...images[symbol] } : null;
  }
  return Object.freeze({ describe });
