"""Prepare offline text IPA for lesson words and the 24 voice-trial prompts."""
from pathlib import Path
import json

from phonetic_engine import PhoneticAnalyzer


def main():
    root = Path(__file__).resolve().parents[1]
    source = (root / "app/content.js").read_text()
    content = json.loads(source.split("globalThis.EGL_CONTENT =", 1)[1].strip().removesuffix(";"))
    resources = root / "speech-training/resources"
    evaluation = json.loads((resources / "evaluation-prompts.json").read_text())
    texts = {p["text"] for p in evaluation["prompts"]}
    texts.update(lesson["speak"]["model"] for lesson in content["lessons"])
    for word in content["glossary"]:
        texts.update([word["en"], word["example"]])
    analyzer = PhoneticAnalyzer()
    data = {text: analyzer.annotate_text(text, "en-us") for text in sorted(texts)}
    payload = {"schema_version": 1, "created_on": "2026-10-24", "timezone": "Asia/Bangkok",
        "purpose": "Offline expected IPA from text; no audio analysis or pronunciation grade",
        "accent": "en-us", "texts": data}
    resources.mkdir(parents=True, exist_ok=True)
    (resources / "phonetics.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
    # A local classic script works when lessons are opened directly via file://.
    js = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c")
    (root / "app/phonetic-data.js").write_text("/* Expected IPA from text only. Generated by speech-training/build_phonetic_data.py. */\nglobalThis.EGL_PHONETIC_DATA = " + js + ";\n")
    print(f"Prepared offline IPA for {len(data)} unique English texts")


if __name__ == "__main__":
    main()
